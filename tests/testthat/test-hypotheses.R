  expect_null(common_overall(y, mk(c(-2, -1), c(0, 0))))
  expect_null(common_overall(NULL, r))
})

test_that("SEDA pools both groups of a gap with common grade weights", {
  g <- function(grade, wh, bl, subject = "math") data.frame(leaid = "0100001", state = "AL", sy_end = 2011L, subject = subject, grade = grade,
    mn_all = 0, se_all = 0.1, mn_wh = wh[1], se_wh = wh[2], mn_bl = bl[1], se_bl = bl[2], mn_hi = NA, se_hi = NA, stringsAsFactors = FALSE)
  x <- rbind(g(3, c(0.5, 0.1), c(-0.3, 0.2)), g(4, c(0.7, 0.3), c(0.1, 0.1)))
  p <- seda_pool(x)
  w <- c(1 / (0.1^2 + 0.2^2), 1 / (0.3^2 + 0.1^2))
  expect_equal(p$mn_bl_b_black_white, sum(w * c(-0.3, 0.1)) / sum(w))
  expect_equal(p$mn_wh_b_black_white, sum(w * c(0.5, 0.7)) / sum(w))
  expect_equal(p$se_bl_b_black_white, sqrt(sum(w^2 * c(0.2, 0.1)^2)) / sum(w))
  expect_equal(p$grades_b_black_white, 2L)
  rg <- seda_race_gaps(rbind(p, transform(p, subject = "rla")))
  bw <- rg[rg$gap == "b_black_white", ]
  expect_equal(bw$v_math, sum(w * c(-0.3, 0.1)) / sum(w) - sum(w * c(0.5, 0.7)) / sum(w))
  expect_equal(bw$se_math, 1 / sqrt(sum(w)))
  expect_false(isTRUE(all.equal(p$mn_wh, p$mn_wh_b_black_white)))
})

