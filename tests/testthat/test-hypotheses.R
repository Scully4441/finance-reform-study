test_that("randomization inference enumerates small assignment sets and draws distinct ones otherwise", {
  expect_equal(ri_assignment_count(5, c(2011, 2011, 2013)), choose(5, 3) * factorial(3) / factorial(2))
  en <- ri_enumerate(5, c(2011, 2011, 2013))
  expect_equal(length(en), 30L)
  keys <- vapply(en, paste, "", collapse = ",")
  expect_false(anyDuplicated(keys) > 0)
  expect_true(all(vapply(en, function(a) sum(a == 2011) == 2 && sum(a == 2013) == 1 && sum(a == 0) == 2, TRUE)))
  set.seed(seed_for("test hypotheses ri draws"))
  dr <- ri_draw_unique(12, c(2011, 2012, 2013), 300L)
  expect_equal(length(dr), 300L)
  expect_false(anyDuplicated(vapply(dr, paste, "", collapse = ",")) > 0)
  expect_equal(ri_assignments(5, c(2011, 2011, 2013), 1000L)$method, "enumerated")
  expect_equal(ri_assignments(12, c(2011, 2012, 2013), 100L)$method, "drawn without duplicate assignments")
  expect_equal(ri_pvalue_exact(c(-2, -1, 0.5, 1, 3), 1), 0.8)
  f <- run_cs(sim()$panel, ~x1, seed_step = "test hypotheses ri")
  r_en <- ri_overall(f$fit, 10000L, "test hypotheses ri enum", parallel = FALSE)
  expect_equal(r_en$method, "enumerated")
