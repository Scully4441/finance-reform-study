long_sim <- function(years = 2008:2020, drop_years = integer(), effect = 0.1, n = 12) {
  ty <- c(2012L, 2012L, 2014L, 2014L, NA, NA, NA, NA, NA)
  ev <- data.frame(state = sprintf("S%02d", seq_along(ty)), treat_year = ty,
                   group = ifelse(is.na(ty), "never", "treated"), stringsAsFactors = FALSE)
  set.seed(seed_for("test hypotheses sim"))
  d <- expand.grid(k = seq_len(n), state = ev$state, sy_end = years, stringsAsFactors = FALSE)
  d <- d[!d$sy_end %in% drop_years, , drop = FALSE]
  d$unit <- paste(d$state, d$k)
  u <- sort(unique(d$unit)); x <- stats::rnorm(length(u))
  d$x1 <- x[match(d$unit, u)]
  tyd <- ev$treat_year[match(d$state, ev$state)]
  d$y <- 0.3 * d$x1 + ifelse(!is.na(tyd) & d$sy_end >= tyd, effect * (d$sy_end - tyd + 1), 0) + stats::rnorm(nrow(d), sd = 0.02)
  attach_cohorts(d[order(d$unit, d$sy_end), ], cohort_coding(ev, sort(unique(d$sy_end))), "unit")$panel
}

test_that("the growth contrast G is formed from the event-time estimates and their influence function", {
  f <- run_cs(long_sim(), ~x1, seed_step = "test hypotheses growth", allow_unbalanced_panel = TRUE)
  expect_equal(f$status, "ok")
  inf <- cs_influence(f$fit)
  g <- growth_contrast(inf)
  ev <- f$event
  manual <- mean(ev$att[ev$e %in% 4:8 & !is.na(ev$se)]) - mean(ev$att[ev$e %in% 0:3 & !is.na(ev$se)])
  expect_equal(g$estimate, manual, tolerance = 1e-10)
  expect_equal(g$early, 0:3)
  expect_equal(g$late, 4:8)
  expect_gt(g$estimate, 0.3)
  set.seed(seed_for("test hypotheses webb"))
  w <- webb_weights(length(inf$states), 499L)
  gt <- growth_test(inf, w)
  expect_true(gt$row$ci_lo <= g$estimate && gt$row$ci_hi >= g$estimate)
  expect_equal(gt$row$early_event_times, "0 1 2 3")
  expect_equal(length(gt$t_boot), 499L)
  gc <- growth_cohorts(f$fit)
  expect_equal(gc$cohorts_early, 2L)
  expect_equal(gc$cohorts_late, 2L)
  expect_equal(gc$treated_states_early, 4L)
  hg <- honest_growth(inf, c(0, 1))
  expect_true(all(c("mbar", "lb", "ub", "status", "event_block") %in% names(hg)))
  og <- hg[hg$method %in% "original", , drop = FALSE]
  expect_equal(nrow(og), 1L)
  expect_equal(og$status, "ok")
  expect_equal((og$lb + og$ub) / 2, g$estimate, tolerance = 1e-3)
  expect_setequal(hg$mbar[!is.na(hg$mbar)], c(0, 1))
  expect_null(growth_weights(0:3))
  expect_equal(growth_weights(c(-2, 0, 1, 4)), c(0, -0.5, -0.5, 1))
  expect_true(is.na(growth_from_events(0:3, c(1, 2, 3, 4))))
  expect_equal(growth_from_events(c(0, 1, 4, 5, 6), c(1, 3, 4, 6, NA)), 3)
  gi <- growth_infer(list(a = list(fit = f$fit, ref = -1L), b = list(fit = NULL, ref = -1L)), w, inf$states, c(0, 1))
  expect_equal(gi$rows$a$status, "ok")
  expect_equal(gi$rows$b$status, "no influence function")
  expect_equal(gi$rows$a$att, g$estimate, tolerance = 1e-12)
  expect_equal(names(gi$honest), "a")
  rw <- rw_stepdown(c(gt$row$t, gt$row$t / 2), cbind(gt$t_boot, gt$t_boot))
  expect_true(all(rw >= gt$row$p_value - 1e-12))
})

test_that("the missing event times of a model are listed with the reason", {
  f <- run_cs(long_sim(drop_years = c(2015L, 2017L)), ~x1, seed_step = "test hypotheses gaps", allow_unbalanced_panel = TRUE)
  eg <- event_time_gaps(f$fit, 2008:2020)
  expect_true(is.data.frame(eg))
  expect_true(all(c("event_time", "reason", "detail") %in% names(eg)))
  expect_true(all(eg$reason %in% c("no cohort", "no district-year", "no state-year", "not estimable")))
  expect_null(event_time_gaps(run_cs(long_sim(), ~x1, seed_step = "test hypotheses gaps full", allow_unbalanced_panel = TRUE)$fit, 2008:2020))
})

test_that("the agreement criterion and the verdicts follow Section 12", {
  sec <- data.frame(name = SECONDARY4, att = c(0.10, 0.12, 0.08, 0.11), status = "ok", stringsAsFactors = FALSE)
  var <- data.frame(name = c("sample_r5", "tested_weighted"), att = c(0.09, 0.13), status = "ok", stringsAsFactors = FALSE)
  ok <- agreement_criterion(0.1, 0.05, 0.15, sec, var)
  expect_true(ok$holds)
  expect_equal(ok$estimators, "holds")
  expect_equal(ok$secondary_estimable, 4L)
  bad <- agreement_criterion(0.1, 0.05, 0.15, transform(sec, att = c(0.10, -0.02, 0.08, 0.11)), var)
  expect_false(bad$holds)
  expect_equal(bad$estimators, "fails")
  expect_match(bad$disagreeing, "imputation")
  few <- agreement_criterion(0.1, 0.05, 0.15, transform(sec, status = c("ok", "ok", "error: x", "error: y")), var)
  expect_false(few$holds)
  expect_match(few$estimators, "^not evaluated")
  skip_one <- agreement_criterion(0.1, 0.05, 0.15, transform(sec, status = c("ok", "ok", "ok", "error: y"), att = c(0.1, 0.1, 0.1, -5)), var)
  expect_true(skip_one$holds)
  vfail <- agreement_criterion(0.1, 0.05, 0.15, sec, transform(var, att = c(0.09, 0.2)))
  expect_equal(vfail$variants, "fails")
  expect_false(vfail$holds)
  novar <- agreement_criterion(0.1, 0.05, 0.15, sec, var[0, ])
  expect_true(novar$holds)

  b <- function(lb, ub, status = "ok") data.frame(mbar = 1, lb = lb, ub = ub, status = status)
  expect_equal(verdict_overall(b(0.01, 0.2), TRUE), "supported")
  expect_equal(verdict_overall(b(0.01, 0.2), FALSE), "not supported")
  expect_equal(verdict_overall(b(-0.3, -0.01), TRUE), "contradicted")
  expect_equal(verdict_overall(b(-0.3, 0.2), TRUE), "not supported")
  expect_equal(verdict_overall(NULL, TRUE), "not evaluable")
  expect_equal(verdict_overall(b(NA, NA, "empty bound set: no value on the grid was accepted"), TRUE), "not evaluable")

  h <- data.frame(mbar = c(NA, 0, 0.5, 1, 1.5, 2), lb = c(0.05, 0.06, 0.03, 0.01, -0.02, -0.05),
                  ub = c(0.2, 0.19, 0.22, 0.25, 0.3, 0.35), status = "ok")
  expect_equal(largest_mbar_excluding_zero(h), 1)
  expect_true(is.na(largest_mbar_excluding_zero(transform(h, lb = -1))))
  expect_equal(bound_row(h, 0)$lb, 0.06)
  expect_equal(bound_text(bound_row(h, 1)), "[0.010, 0.250]")
  expect_equal(bound_text(NULL), "no bound set")

  g_ok <- data.frame(status = "ok")
  expect_equal(verdict_growth(g_ok, b(0.02, 0.3), 0.1, c(0.1, 0.2, NA, 0.05)), "supported")
  expect_equal(verdict_growth(g_ok, b(0.02, 0.3), 0.1, c(0.1, -0.2, NA, 0.05)), "not supported")
  expect_equal(verdict_growth(g_ok, b(0.02, 0.3), -0.1, c(0.1, 0.2)), "not supported")
  expect_equal(verdict_growth(g_ok, b(-0.02, 0.3), 0.1, c(0.1, 0.2)), "not supported")
  expect_equal(verdict_growth(data.frame(status = "no estimated event time in one of the two windows"), b(0.02, 0.3), 0.1, 1), "not evaluable")
  expect_equal(verdict_growth(g_ok, NULL, 0.1, 1), "not evaluable")

  d <- function(rlo, rhi, lo, hi) data.frame(revenue_ci_lo = rlo, revenue_ci_hi = rhi, ci_lo = lo, ci_hi = hi)
  expect_equal(verdict_dose(d(0.2, 1, 0.01, 0.3)), "supported")
  expect_equal(verdict_dose(d(0.2, 1, -0.01, 0.3)), "not supported")
  expect_equal(verdict_dose(d(-0.2, 1, NA, NA)), "not evaluable")
  expect_equal(verdict_dose(NULL), "not evaluable")
  expect_equal(unname(HYPOTHESIS_OF_GAP[c("a_poverty", "b_black_white", "c_hispanic_white", "grad_black_white")]),
               c("H1", "H2", "H3", "H2"))
})

