test_that("the dose ratio uses the overall averages over the same event times in both stages", {
  mk <- function(e, att) list(egt = e, att_egt = att, se_egt = rep(0.1, length(e)), n = 3L, states = c("S1", "S2", "S3"),
                              overall_att = 99, scores = cbind(matrix(seq_len(3 * length(e)) / 10, 3, dimnames = list(NULL, paste0("e", e))),
                                                               overall = 0))
  y <- mk(c(-1, 0, 1, 2), c(0, 0.2, 0.4, 0.6)); r <- mk(c(-1, 0, 1), c(0, 1, 3))
  cm <- common_overall(y, r)
  expect_equal(cm$event_times, c(0, 1))
